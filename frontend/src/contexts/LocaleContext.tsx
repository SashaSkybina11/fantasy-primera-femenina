const dictionaries: Record<Locale, Record<TranslationKey, string>> = {
  es: spanish,
  uk: ukrainian,
  en: english,
};

type LocaleContextValue = {
  locale: Locale;
  setLocale: (locale: Locale) => void;
  t: (
    key: TranslationKey,
    variables?: Record<string, string | number>,
  ) => string;
};

const LocaleContext = createContext<LocaleContextValue | null>(null);

function initialLocale(): Locale {
  return getStoredLocale();
}

export function LocaleProvider({ children }: { children: React.ReactNode }) {
  const [locale, setLocale] = useState<Locale>(initialLocale);

  useEffect(() => {
    toast.dismiss();
    const invalid = (event: Event) => {
      const input = event.target;
      if (
        input instanceof HTMLInputElement ||
        input instanceof HTMLTextAreaElement ||
        input instanceof HTMLSelectElement
      )
        input.setCustomValidity(dictionaries[locale]["validation.invalid"]);
    };
    const clear = (event: Event) => {
      const input = event.target;
      if (
        input instanceof HTMLInputElement ||
        input instanceof HTMLTextAreaElement ||
        input instanceof HTMLSelectElement
      )
        input.setCustomValidity("");
    };
    document
      .querySelectorAll("input, textarea, select")
      .forEach((input) => (input as HTMLInputElement).setCustomValidity(""));
    document.addEventListener("invalid", invalid, true);
    document.addEventListener("input", clear, true);
    document.documentElement.lang = locale;
    document.title = dictionaries[locale]["brand.title"];
    document
      .querySelectorAll(
        'meta[name="description"], meta[property="og:description"], meta[name="twitter:description"]',
      )
      .forEach((meta) => {
        meta.setAttribute("content", dictionaries[locale]["home.description"]);
      });
    document
      .querySelector('meta[property="og:locale"]')
      ?.setAttribute(
        "content",
        { es: "es_ES", uk: "uk_UA", en: "en_GB" }[locale],
      );
    localStorage.setItem(storageKey, locale);
    return () => {
      document.removeEventListener("invalid", invalid, true);
      document.removeEventListener("input", clear, true);
    };
  }, [locale]);

  const value = useMemo<LocaleContextValue>(
    () => ({
      locale,
      setLocale: (next) => {
        localStorage.setItem(storageKey, next);
        setLocale(next);
      },
      t: (key, variables = {}) =>
        dictionaries[locale][key].replace(
          /{{(\w+)}}/g,
          (_match, name: string) => String(variables[name] ?? ""),
        ),
    }),
    [locale],
  );

  return (
    <LocaleContext.Provider value={value}>{children}</LocaleContext.Provider>
  );
}

export function useLocale() {
  const context = useContext(LocaleContext);
  if (!context) throw new Error("useLocale must be used inside LocaleProvider");
  return context;
}

export function getStoredLocale(): Locale {
  const stored = localStorage.getItem(storageKey);
  return stored === "uk" || stored === "en" ? stored : "es";
}
